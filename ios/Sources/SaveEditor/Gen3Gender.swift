  private static let cfruRatios: [UInt8] = {
    let hex = cfruRatioHex.filter { !$0.isWhitespace }
    var out: [UInt8] = []
    out.reserveCapacity(hex.count / 2)
    var hi: UInt8? = nil
    for ch in hex.utf8 {
      let v: UInt8
      if (48...57).contains(ch) { v = ch - 48 }
      else if (97...102).contains(ch) { v = ch - 87 }
      else if (65...70).contains(ch) { v = ch - 55 }
      else { continue }
      if let h = hi { out.append(h << 4 | v); hi = nil } else { hi = v }
    }
    return out
  }()

  private static func parse(_ blob: String) -> [Int: Int] {
    var out: [Int: Int] = [:]
    for line in blob.split(separator: "\n", omittingEmptySubsequences: true) {
      guard let bar = line.firstIndex(of: "|"),
            let id = Int(line[line.startIndex..<bar]),
            let ratio = Int(line[line.index(after: bar)...]) else { continue }
      out[id] = ratio
    }
    return out
  }

  private static let retailMap = parse(ratioRetail)
  private static let nationalMap = parse(ratioNational)

  /// Species gender ratio byte (0 = always ♂, 254 = always ♀, 255 = —).
  static func ratio(species: Int, tables: Gen3Tables) -> Int {
    switch tables {
    case .retail:
      return retailMap[species] ?? nationalMap[species] ?? 127
    case .unbound:
      // Unbound uses CFRU/DPE species ids — not National Dex numbers.
      if species >= 0, species < cfruRatios.count {
        return Int(cfruRatios[species])
      }
      if let nat = Gen3Names.nationalNumber(species: species, tables: .unbound) {
        return nationalMap[nat] ?? retailMap[nat] ?? 127
      }
      return 127
    case .modernEmerald:
      if let nat = Gen3Names.nationalNumber(species: species, tables: .modernEmerald) {
        return nationalMap[nat] ?? retailMap[nat] ?? 127
      }
      return retailMap[species] ?? nationalMap[species] ?? 127
    case .national, .hns:
      return nationalMap[species] ?? retailMap[species] ?? 127
    case .yellow, .crystal, .polished, .prism:
      return nationalMap[species] ?? 127
    }
  }

  static func gender(species: Int, personality: Int, tables: Gen3Tables) -> Gen3MonGender {
    let r = ratio(species: species, tables: tables)
    if r == 255 { return .genderless }
    if r == 0 { return .male }
    if r == 254 { return .female }
    return (personality & 0xFF) < r ? .female : .male
  }

  /// Allowed genders for this species (fixed ratios only offer one).
  static func options(species: Int, tables: Gen3Tables) -> [Gen3MonGender] {
    let r = ratio(species: species, tables: tables)
    switch r {
    case 255: return [.genderless]
    case 0: return [.male]
    case 254: return [.female]
    default: return [.male, .female]
    }
  }

  /// Low byte of PID that yields `gender`, keeping as much of `seed` as possible.
  static func personalityByte(for gender: Gen3MonGender, species: Int, tables: Gen3Tables, seed: Int = 0) -> Int {
    let r = ratio(species: species, tables: tables)
    switch gender {
    case .genderless, .male where r == 0, .female where r == 254:
      return seed & 0xFF
    case .male:
      if r >= 255 { return seed & 0xFF }
      // Need byte >= r
      let b = max(r, 1)
      return min(255, b)
    case .female:
      if r <= 0 { return seed & 0xFF }
      return max(0, r - 1)
    }
  }
