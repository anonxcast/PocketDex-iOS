  private static func parse(_ blob: String) -> [Int: [Int]] {
    var out: [Int: [Int]] = [:]
    for line in blob.split(separator: "\n", omittingEmptySubsequences: true) {
      guard let bar = line.firstIndex(of: "|") else { continue }
      guard let id = Int(line[line.startIndex..<bar]) else { continue }
      let parts = line[line.index(after: bar)...].split(separator: ",").compactMap { Int($0) }
      guard parts.count == 6 else { continue }
      out[id] = parts
    }
    return out
  }

  private static let retailMap: [Int: [Int]] = parse(baseStatsRetail)
  private static let nationalMap: [Int: [Int]] = parse(baseStatsNational)

  /// Six stats for `species` under the active name tables. Falls back to national, then a generic mid-tier mon.
  static func stats(species: Int, tables: Gen3Tables) -> [Int] {
    let fallback = [70, 70, 70, 70, 70, 70]
    switch tables {
    case .retail:
      return retailMap[species] ?? nationalMap[species] ?? fallback
    case .unbound, .modernEmerald:
      // Unbound / Modern Emerald ids → National Dex before looking up base stats.
      if let nat = Gen3Names.nationalNumber(species: species, tables: tables) {
        return nationalMap[nat] ?? retailMap[nat] ?? fallback
      }
      return nationalMap[species] ?? retailMap[species] ?? fallback
    case .national:
      return nationalMap[species] ?? retailMap[species] ?? fallback
    case .yellow, .crystal, .polished:
      return nationalMap[species] ?? fallback
    }
  }

  /// Gen 3 battle-stat formula (nature ±10%). Order: HP, Atk, Def, Spe, SpA, SpD.
  static func partyStats(species: Int, level: Int, ivs: [Int], evs: [Int], nature: Int, tables: Gen3Tables) -> [Int] {
    let base = stats(species: species, tables: tables)
    let iv = (ivs + [0, 0, 0, 0, 0, 0]).prefix(6).map { max(0, min(31, $0)) }
    let ev = (evs + [0, 0, 0, 0, 0, 0]).prefix(6).map { max(0, min(255, $0)) }
    let lv = max(1, min(100, level))
    let n = ((nature % 25) + 25) % 25
    let up = n / 5    // 0 Atk … 4 SpD
    let down = n % 5
    // Map our index → nature axis (HP has none).
    let axis: [Int?] = [nil, 0, 1, 2, 3, 4]
    var out = [Int](repeating: 0, count: 6)
    for i in 0..<6 {
      let raw = ((2 * base[i] + iv[i] + ev[i] / 4) * lv) / 100
      if i == 0 {
        out[i] = raw + lv + 10
        continue
      }
      var s = raw + 5
      if let a = axis[i], up != down {
        if a == up { s = s * 11 / 10 }
        if a == down { s = s * 9 / 10 }
      }
      out[i] = max(1, s)
    }
    return out
  }
