  static func entry(species: Int, gen5: Bool) -> Entry? {
    let table = gen5 ? gen5Bytes : gen4Bytes
    guard species >= 1, (species - 1) * 7 + 7 <= table.count else { return nil }
    let o = (species - 1) * 7
    return Entry(base: (0..<6).map { Int(table[o + $0]) }, growth: Int(table[o + 6]))
  }

  private static let gen4Bytes: [UInt8] = decode(gen4Hex)
  private static let gen5Bytes: [UInt8] = decode(gen5Hex)

  private static func decode(_ hex: String) -> [UInt8] {
    var out: [UInt8] = []
    out.reserveCapacity(hex.utf8.count / 2)
    var hi: UInt8? = nil
    for c in hex.utf8 {
      guard (c >= 48 && c <= 57) || (c >= 97 && c <= 102) else { continue }
      let v: UInt8 = c >= 97 ? c - 87 : c - 48
      if let h = hi { out.append(h << 4 | v); hi = nil } else { hi = v }
    }
    return out
  }

