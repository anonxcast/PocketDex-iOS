#!/usr/bin/env python3
"""Generate SmartIslandTalkTipsGen.swift from Android GuideAreas* PEOPLE rows.

Line format in Kotlin: mapsec|kind|id|flag|qty|wants|where
We keep GIFT/KEY/MON/EGG/TRADE only (who to talk to), compact as:
  guideId|mapsec|kind|id|qty|wants|where
"""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
KT = ROOT / "upstream/app/src/main/kotlin/com/pokedaisy/app/companion/data"
OUT = ROOT / "ios/Sources/Companion/Generated/SmartIslandTalkTipsGen.swift"

PEOPLE = {"GIFT", "KEY", "MON", "EGG", "TRADE"}

# Kotlin symbol → Swift guide key (matches SmartIslandTalkTips.guideKey).
SOURCES: list[tuple[str, str]] = [
    ("GUIDE_AREAS_FIRERED_RAW", "firered"),
    ("GUIDE_AREAS_LEAFGREEN_RAW", "leafgreen"),
    ("GUIDE_AREAS_EMERALD_RAW", "emerald"),
    ("GUIDE_AREAS_RUBY_SAPPHIRE_RAW", "ruby_sapphire"),
    ("GUIDE_AREAS_UNBOUND_RAW", "unbound"),
    ("GUIDE_AREAS_RADICAL_RED_RAW", "radical_red"),
    ("GUIDE_AREAS_HEART_AND_SOUL_RAW", "heart_and_soul"),
    ("GUIDE_AREAS_ROCKET_EDITION_RAW", "rocket_edition"),
    ("GUIDE_AREAS_EMERALD_LEGACY_RAW", "emerald_legacy"),
    ("GUIDE_AREAS_ODYSSEY_RAW", "odyssey"),
    ("GUIDE_AREAS_GAIA_RAW", "gaia"),
    ("GUIDE_AREAS_CRYSTAL_RAW", "crystal"),
    ("GUIDE_AREAS_POLISHED_CRYSTAL_RAW", "polished_crystal"),
]


def extract_raw(text: str, symbol: str) -> list[str]:
    # listOf( """ ... """ ) or listOf( "a", "b" )
    m = re.search(
        rf"internal val {re.escape(symbol)}\s*:\s*List<String>\s*=\s*listOf\((.*?)\)\s*\n",
        text,
        re.S,
    )
    if not m:
        return []
    block = m.group(1)
    # Prefer the big triple-quoted blob if present.
    tri = re.search(r'"""(.*?)"""', block, re.S)
    if tri:
        return [ln.strip() for ln in tri.group(1).splitlines() if "|" in ln]
    out = []
    for ln in block.splitlines():
        ln = ln.strip().rstrip(",")
        if ln.startswith('"') and "|" in ln:
            out.append(ln.strip('"'))
    return out


def main() -> int:
    files = list(KT.glob("GuideAreas*Gen.kt")) + [
        KT / "GuideCrystalGen.kt",
        KT / "GuidePolishedCrystalGen.kt",
        KT / "GuideCrystalLegacyGen.kt",
    ]
    texts = {p.name: p.read_text(encoding="utf-8", errors="ignore") for p in files if p.exists()}
    combined = "\n".join(texts.values())

    rows: list[str] = []
    for symbol, guide in SOURCES:
        raw = extract_raw(combined, symbol)
        if not raw:
            print(f"warn: missing {symbol}", file=sys.stderr)
            continue
        n = 0
        for ln in raw:
            parts = ln.split("|")
            if len(parts) < 7:
                continue
            mapsec, kind, iid, _flag, qty, wants, where = parts[:7]
            if kind not in PEOPLE:
                continue
            where = where.replace("\\", "").strip()
            rows.append(f"{guide}|{mapsec}|{kind}|{iid}|{qty}|{wants}|{where}")
            n += 1
        print(f"{guide}: {n} people tips")

    # Swift raw string — real newlines (don't emit \\n escapes).
    body = "\n".join(rows).replace("\\", "\\\\")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        f"""\
// Generated by scripts/gen_smart_island_talk_tips.py — do not edit by hand.
import Foundation

enum SmartIslandTalkTipsGen {{
  /// guide|mapsec|kind|id|qty|wants|where — PEOPLE tips only (GIFT/KEY/MON/EGG/TRADE).
  static let rawBlob: String = #\"\"\"
{body}
\"\"\"#
}}
""",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(rows)} rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
