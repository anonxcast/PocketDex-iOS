#!/usr/bin/env python3
"""Generate ios/Sources/Companion/Gen3Tables*.swift from the upstream Kotlin name tables.

Tables are emitted as compact "id|name" multi-line raw strings and parsed lazily at runtime
(fast to compile, no giant dictionary literals).
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "upstream/app/src/main/kotlin/com/pokedaisy/app/companion/data"
OUT = ROOT / "ios/Sources/Companion"

NAME_RE = re.compile(r'^\s*(\d+) to "((?:[^"\\]|\\.)*)"', re.M)
MOVE_RE = re.compile(r'^\s*(\d+) to MoveInfo\("((?:[^"\\]|\\.)*)"', re.M)
SEC_RE = re.compile(r'^\s*(\d+) to MapSecInfo\("((?:[^"\\]|\\.)*)"', re.M)


def parse(path, rx):
    text = (DATA / path).read_text()
    out = {}
    for m in rx.finditer(text):
        out[int(m.group(1))] = m.group(2).replace('\\"', '"')
    return out


def blob(name, table):
    lines = "\n".join(f"{k}|{v}" for k, v in sorted(table.items()))
    return f'  static let {name}: String = #"""\n{lines}\n"""#\n'


def main():
    species = parse("SpeciesNames.kt", NAME_RE)
    species_unb = parse("SpeciesNamesUnbound.kt", NAME_RE)
    national = parse("SpeciesNamesNationalDex.kt", NAME_RE)
    items = parse("ItemNames.kt", NAME_RE)
    items[375] = "Magma Emblem"
    items[376] = "Old Sea Map"
    # Prettier TM / HM labels.
    for k, v in list(items.items()):
        if re.fullmatch(r"Tm\d+", v):
            items[k] = "TM" + v[2:]
        elif re.fullmatch(r"Hm\d+", v):
            items[k] = "HM" + v[2:]
    items_unb = parse("ItemNamesUnbound.kt", NAME_RE)
    moves = parse("MoveData.kt", MOVE_RE)
    moves_unb = parse("MoveDataUnbound.kt", MOVE_RE)
    sec_fr = parse("MapSecData.kt", SEC_RE)
    sec_em = parse("MapSecDataEmerald.kt", SEC_RE)
    sec_unb = parse("MapSecDataUnbound.kt", SEC_RE)

    body = "// Generated by scripts/gen_gen3_tables.py from upstream/ Kotlin tables. Do not hand-edit.\n\n"
    body += "enum Gen3TableBlobs {\n"
    body += blob("speciesRetail", species)
    body += blob("speciesUnbound", species_unb)
    body += blob("speciesNational", national)
    body += blob("itemsRetail", items)
    body += blob("itemsUnbound", items_unb)
    body += blob("movesRetail", moves)
    body += blob("movesUnbound", moves_unb)
    body += blob("mapSecFireRed", sec_fr)
    body += blob("mapSecEmerald", sec_em)
    body += blob("mapSecUnbound", sec_unb)
    body += "}\n"
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "Gen3TableBlobs.swift").write_text(body)
    print({k: len(v) for k, v in dict(species=species, unb=species_unb, nat=national, items=items,
                                      items_unb=items_unb, moves=moves, moves_unb=moves_unb,
                                      sec_fr=sec_fr, sec_em=sec_em, sec_unb=sec_unb).items()})


if __name__ == "__main__":
    main()
